# 차변/대변 × 유형 -> 결합관계(거래 8요소)
_COMBO = {
    ("debit", ASSET): "자산의 증가", ("credit", ASSET): "자산의 감소",
    ("debit", LIABILITY): "부채의 감소", ("credit", LIABILITY): "부채의 증가",
    ("debit", EQUITY): "자본의 감소", ("credit", EQUITY): "자본의 증가",
    ("debit", REVENUE): "수익의 감소", ("credit", REVENUE): "수익의 발생",
    ("debit", EXPENSE): "비용의 발생", ("credit", EXPENSE): "비용의 감소",
    # 자산에서 빼 주는 계정이라 방향이 자산과 반대로 읽힌다
    ("debit", CONTRA): "자산의 증가", ("credit", CONTRA): "자산의 감소",
}


def clean(name):
    """'미지급금(우리카드(법인))' -> '미지급금'. 거래처·코드 괄호를 떼어낸다."""
    import re
    # "현금 → 일반전표 삭제" 처럼 처리 지시가 뒤에 붙는 경우가 있다.
    n = re.split(r"→|->", name or "")[0]
    n = re.sub(r"\(.*", "", n)
    n = re.sub(r"[\[\]0-9]", "", n)
    n = re.sub(r"\s+", "", n).strip("()· ")
    return ALIASES.get(n, n)


def look_up(name):
    """계정 이름 -> (유형, 뜻). 사전에 없으면 (None, None)."""
    return ACCOUNTS.get(clean(name), (None, None))


def combo_of(side, name):
    """'debit'/'credit' + 계정 이름 -> '자산의 증가' 같은 결합관계. 모르면 None."""
    kind, _ = look_up(name)
    return _COMBO.get((side, kind)) if kind else None


def describe(entry_sets):
    """분개 전체를 '자산의 증가 / 부채의 증가' 꼴로 요약한다.

    같은 결합관계가 여러 줄이면 한 번만 쓰고 (2건)을 붙인다.
    """
    def side_text(entries, side):
        seen = []
        for e in entries:
            c = combo_of(side, e["account"])
            if c and c not in seen:
                seen.append(c)
        out = []
        for c in seen:
            n = sum(1 for e in entries if combo_of(side, e["account"]) == c)
            out.append(f"{c} ({n}건)" if n > 1 else c)
        return " + ".join(out)

    parts = []
    for s in entry_sets:
        left = side_text(s["debit"], "debit")
        right = side_text(s["credit"], "credit")
        if left or right:
            parts.append(f"{left} / {right}")
    return parts


def glossary(entry_sets):
    """이 분개에 쓰인 계정들의 뜻을 [(이름, 유형, 뜻)] 로. 사전에 없으면 건너뛴다."""
    out, seen = [], set()
    for s in entry_sets:
        for e in s["debit"] + s["credit"]:
            n = clean(e["account"])
            if n in seen:
                continue
            seen.add(n)
            kind, text = look_up(n)
            if kind:
                out.append((n, kind, text))
    return out


# 한국어는 단어가 붙어 있어서 그냥 찾으면 엉뚱한 데서 걸린다. "현금배당"의 현금,
# "완제품"의 제품, "기말원재료재고액"의 원재료처럼. 그래서 앞뒤 경계를 본다.
#  - 앞: 한글이 붙어 있으면 더 긴 낱말의 일부다 (완제품)
#  - 뒤: 한글이 붙어 있으면 역시 일부다. 단 조사는 예외 (미수금'은', 토지'를')
_PARTICLES_1 = set("은는이가을를의에와과로도만나")
_PARTICLES_2 = {"으로", "에서", "부터", "까지", "라고", "이나", "처럼", "보다",
                "에는", "이다", "이며", "으며", "에도", "만을", "으로서", "이란",
                "라는", "이라", "에게", "으나", "이고", "하고", "인가", "등의"}


def _is_hangul(ch):
    return "가" <= ch <= "힣"


def _standalone(text, at, length):
    """text[at:at+length] 가 더 긴 낱말에 묻힌 게 아닌지 본다."""
    if at > 0 and _is_hangul(text[at - 1]):
        return False
    end = at + length
    if end >= len(text) or not _is_hangul(text[end]):
        return True
    if text[end] in _PARTICLES_1:
        return True
    return text[end:end + 2] in _PARTICLES_2


def find_accounts(text, limit=8):
    """글 속에서 계정과목을 찾아 [(이름, 유형, 뜻)] 로. 긴 이름을 먼저 맞춘다.

    이론 문제에 붙일 용도. 같은 자리를 두 번 세지 않으려고 이미 맞은 구간은 지운다.
    """
    if not text:
        return []
    taken = [False] * len(text)
    hits = []
    for name in sorted(ACCOUNTS, key=len, reverse=True):
        at = text.find(name)
        while at >= 0:
            if not any(taken[at:at + len(name)]) and _standalone(text, at, len(name)):
                for k in range(at, at + len(name)):
                    taken[k] = True
                kind, desc = ACCOUNTS[name]
                hits.append((at, name, kind, desc))
                break
            at = text.find(name, at + 1)
    hits.sort()
    return [(n, k, d) for _at, n, k, d in hits[:limit]]


