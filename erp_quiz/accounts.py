    sets = [{"debit": [{"account": "보통예금"}, {"account": "받을어음"}],
             "credit": [{"account": "제품매출"}, {"account": "부가세예수금"}]}]
    assert describe(sets) == ["자산의 증가 (2건) / 수익의 발생 + 부채의 증가"], describe(sets)
