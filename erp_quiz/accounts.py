    assert combo_of("credit", "부가세예수금") == "부채의 증가"
    assert combo_of("debit", "외상매입금") == "부채의 감소"
    assert combo_of("credit", "대손충당금") == "자산의 감소"
    assert clean("미지급금(우리카드(법인))") == "미지급금"
    assert clean("매도가능증권(178)") == "매도가능증권"
