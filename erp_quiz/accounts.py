_SIDE_TAG = __import__("re").compile(r"\((제|판)\)")


def code_of(name):
    """'복리후생비(제)' -> '0511'. 모르는 계정은 None.

    제조원가와 판매관리비는 이름이 같아도 코드가 다르므로 (제)/(판) 꼬리표를
    먼저 본다. clean() 은 괄호를 통째로 떼기 때문에 여기서는 쓸 수 없다.
    """
    base = clean(name)
    m = _SIDE_TAG.search(name or "")
    if m:
        hit = CODES.get("%s(%s)" % (base, m.group(1)))
        if hit:
            return hit
    return CODES.get(base)


def code_note(name):
    """코드가 하나로 안 정해지는 계정이면 그 이유를, 아니면 None."""
    return CODE_NOTES.get(clean(name))

