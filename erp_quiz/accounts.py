def vat_type(code):
    """'51.과세' 또는 '51. 과세' -> (코드, 이름, 매출/매입, 설명). 모르면 None."""
    import re
    m = re.match(r"\s*(\d{2})", code or "")
    if not m or m.group(1) not in VAT_TYPES:
        return None
    name, side, text = VAT_TYPES[m.group(1)]
    return (m.group(1), name, side, text)


# 표기가 갈리는 것들
ALIASES = {
    "세금과공과금": "세금과공과",
    "접대비": "기업업무추진비",
}

# 차변/대변 × 유형 -> 결합관계(거래 8요소)
_COMBO = {
    ("debit", ASSET): "자산의 증가", ("credit", ASSET): "자산의 감소",
    ("debit", LIABILITY): "부채의 감소", ("credit", LIABILITY): "부채의 증가",
    ("debit", EQUITY): "자본의 감소", ("credit", EQUITY): "자본의 증가",
    ("debit", REVENUE): "수익의 감소", ("credit", REVENUE): "수익의 발생",
    ("debit", EXPENSE): "비용의 발생", ("credit", EXPENSE): "비용의 감소",
    # 자산에서 빼 주는 계정이라 방향이 자산과 반대로 읽힌다
    ("debit", CONTRA): "자산의 증가", ("credit", CONTRA): "자산의 감소",
}


def clean(name):
    """'미지급금(우리카드(법인))' -> '미지급금'. 거래처·코드 괄호를 떼어낸다."""
    import re
    # "현금 → 일반전표 삭제" 처럼 처리 지시가 뒤에 붙는 경우가 있다.
    n = re.split(r"→|->", name or "")[0]
    n = re.sub(r"\(.*", "", n)
    n = re.sub(r"[\[\]0-9]", "", n)
    n = re.sub(r"\s+", "", n).strip("()· ")
    return ALIASES.get(n, n)


def look_up(name):
    """계정 이름 -> (유형, 뜻). 사전에 없으면 (None, None)."""
    return ACCOUNTS.get(clean(name), (None, None))


def combo_of(side, name):
    """'debit'/'credit' + 계정 이름 -> '자산의 증가' 같은 결합관계. 모르면 None."""
    kind, _ = look_up(name)
    return _COMBO.get((side, kind)) if kind else None


def describe(entry_sets):
    """분개 전체를 '자산의 증가 / 부채의 증가' 꼴로 요약한다.

    같은 결합관계가 여러 줄이면 한 번만 쓰고 (2건)을 붙인다.
    """
    def side_text(entries, side):
        seen = []
        for e in entries:
            c = combo_of(side, e["account"])
            if c and c not in seen:
                seen.append(c)
        out = []
        for c in seen:
            n = sum(1 for e in entries if combo_of(side, e["account"]) == c)
            out.append(f"{c} ({n}건)" if n > 1 else c)
        return " + ".join(out)

    parts = []
    for s in entry_sets:
        left = side_text(s["debit"], "debit")
        right = side_text(s["credit"], "credit")
        if left or right:
            parts.append(f"{left} / {right}")
    return parts


def glossary(entry_sets):
    """이 분개에 쓰인 계정들의 뜻을 [(이름, 유형, 뜻)] 로. 사전에 없으면 건너뛴다."""
    out, seen = [], set()
    for s in entry_sets:
        for e in s["debit"] + s["credit"]:
            n = clean(e["account"])
            if n in seen:
                continue
            seen.add(n)
            kind, text = look_up(n)
            if kind:
                out.append((n, kind, text))
    return out


