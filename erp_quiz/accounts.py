def why_side(entry_sets):
    """분개 한 줄마다 (자리, 코드, 계정, 결합관계, 이유)를 만든다.

    같은 계정이 여러 번 나와도 한 번만 설명한다. 유형을 모르는 계정은 자리를
    설명할 근거가 없으므로 건너뛴다.
    """
    out, seen = [], set()
    for s in entry_sets:
        for side in ("debit", "credit"):
            for e in s.get(side) or []:
                name = e["account"]
                key = (side, clean(name))
                if key in seen:
                    continue
                seen.add(key)
                combo = combo_of(side, name)
                if not combo:
                    continue
                out.append((SIDE_NAMES[side], code_of(name), clean(name),
                            combo, SIDE_RULE[combo]))
    return out


